-- Core schema (D3, D12).

-- Deliberately simple business tables: they exist so the API has real state to
-- change in the same transaction as the outbox row.
CREATE TABLE payments (
    id           uuid        PRIMARY KEY,
    account_id   text        NOT NULL,
    amount_cents bigint      NOT NULL CHECK (amount_cents > 0),
    currency     text        NOT NULL,
    status       text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE bookings (
    id          uuid        PRIMARY KEY,
    customer_id text        NOT NULL,
    item        text        NOT NULL,
    status      text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE password_changes (
    id         uuid        PRIMARY KEY,
    user_id    text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Event-level state: relay -> broker.
CREATE TABLE outbox_events (
    id              uuid        PRIMARY KEY,                 -- UUIDv7 generated by the application
    event_type      text        NOT NULL,
    aggregate_type  text        NOT NULL,
    aggregate_id    text        NOT NULL,
    payload         jsonb       NOT NULL,
    status          text        NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'PROCESSING', 'RETRYING', 'PUBLISHED', 'DLQ')),
    attempts        int         NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),      -- also the lease expiry while PROCESSING
    last_error      text,
    locked_by       text,
    locked_until    timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    published_at    timestamptz
);

-- The relay's hot query only ever looks at rows that still need work, so the
-- index only contains those. Rows leave it when they become PUBLISHED or DLQ.
CREATE INDEX outbox_ready_idx ON outbox_events (next_attempt_at, id)
    WHERE status IN ('PENDING', 'RETRYING', 'PROCESSING');

-- Per-channel state: broker -> side effect. One row per (event, channel), created
-- in the same transaction as the outbox row.
CREATE TABLE channel_deliveries (
    event_id        uuid        NOT NULL REFERENCES outbox_events (id),
    channel         text        NOT NULL CHECK (channel IN ('email', 'push', 'webhook')),
    status          text        NOT NULL DEFAULT 'PENDING'
                    CHECK (status IN ('PENDING', 'RETRYING', 'DELIVERED', 'DLQ')),
    attempts        int         NOT NULL DEFAULT 0,
    next_attempt_at timestamptz,
    last_error      text,
    delivered_at    timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id, channel)
);

CREATE INDEX channel_deliveries_open_idx ON channel_deliveries (channel, event_id)
    WHERE status IN ('PENDING', 'RETRYING');
CREATE INDEX channel_deliveries_dlq_idx ON channel_deliveries (channel, event_id)
    WHERE status = 'DLQ';

-- API-level idempotency (D12). Written in the same transaction as the business row.
CREATE TABLE api_idempotency (
    key          text        PRIMARY KEY,
    request_hash text        NOT NULL,
    status_code  int,
    response     jsonb,
    created_at   timestamptz NOT NULL DEFAULT now()
);
